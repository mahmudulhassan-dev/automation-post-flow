const defaultApiBase =
  window.location.hostname === "127.0.0.1" || window.location.hostname === "localhost"
    ? "http://127.0.0.1:8080/api"
    : "/api";

const state = {
  apiBase: localStorage.getItem("amanaflow:apiBase") || defaultApiBase,
  language: localStorage.getItem("amanaflow:lang") || "bn",
  plans: []
};

function $(id) {
  return document.getElementById(id);
}

function setText(id, text) {
  const element = $(id);
  if (element) {
    element.textContent = text;
  }
}

function jsonView(data) {
  return `<pre>${JSON.stringify(data, null, 2)}</pre>`;
}

async function apiGet(path) {
  const response = await fetch(`${state.apiBase}${path}`);
  if (!response.ok) {
    throw new Error(`GET ${path} failed: ${response.status}`);
  }
  return response.json();
}

async function apiPost(path, payload) {
  const response = await fetch(`${state.apiBase}${path}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload)
  });
  const data = await response.json();
  if (!response.ok) {
    throw new Error(data.error || `POST ${path} failed`);
  }
  return data;
}

function applyLanguage() {
  const isBn = state.language === "bn";
  setText("heroTitle", isBn ? "নিজস্ব SaaS অটোমেশন প্ল্যাটফর্ম" : "Your own SaaS automation platform");
  setText(
    "heroLead",
    isBn
      ? "এখন থেকে আপনার নিজস্ব কোডবেসে channel integration, billing, auto-renew, payment gateway এবং admin control একসাথে থাকবে।"
      : "From now on, your own codebase controls channel integrations, billing, auto-renew, payment gateways, and admin controls."
  );
  $("langToggle").textContent = isBn ? "EN" : "বাংলা";
  document.documentElement.lang = isBn ? "bn" : "en";
}

function setupLanguageToggle() {
  $("langToggle").addEventListener("click", () => {
    state.language = state.language === "bn" ? "en" : "bn";
    localStorage.setItem("amanaflow:lang", state.language);
    applyLanguage();
  });
  applyLanguage();
}

function setupComposer() {
  const delayInput = $("delay");
  const delayLabel = $("delayValue");
  delayInput.addEventListener("input", () => {
    delayLabel.textContent = delayInput.value;
  });

  $("generateBtn").addEventListener("click", () => {
    const prompt = $("prompt").value.trim();
    if (!prompt) {
      $("generatedPost").textContent = "পোস্টের আইডিয়া লিখুন।";
      return;
    }
    const waitSeconds = Number(delayInput.value || 5);
    const model = $("model").value;
    $("generatedPost").textContent = `Generating with ${model} (${waitSeconds}s)...`;

    window.setTimeout(() => {
      const content =
        `🎯 ${prompt}\n\n` +
        `✨ Generated by ${model}\n` +
        `Amanaflow branded reply policy active.\n` +
        `Auto-delay সেট করা আছে ${waitSeconds} সেকেন্ড।\n\n` +
        `#Amanaflow #Automation #Business`;
      $("generatedPost").textContent = content;
    }, waitSeconds * 1000);
  });
}

function setupApiConfig() {
  $("apiBase").value = state.apiBase;

  $("saveApiBase").addEventListener("click", () => {
    const newBase = $("apiBase").value.trim();
    if (!newBase) return;
    state.apiBase = newBase.replace(/\/$/, "");
    localStorage.setItem("amanaflow:apiBase", state.apiBase);
    setText("apiHealth", `Saved: ${state.apiBase}`);
  });

  $("checkApi").addEventListener("click", async () => {
    try {
      const data = await apiGet("/health");
      setText("apiHealth", `API OK: ${new Date(data.now).toLocaleString()}`);
    } catch (error) {
      setText("apiHealth", `API error: ${error.message}`);
    }
  });
}

async function loadPlans() {
  try {
    const data = await apiGet("/plans");
    state.plans = data.plans || [];
    const planSelect = $("billingPlan");
    planSelect.innerHTML = "";
    state.plans.forEach((plan) => {
      const option = document.createElement("option");
      option.value = plan.code;
      option.textContent = `${plan.name} - ৳${plan.price_bdt}/${plan.interval_months}m`;
      planSelect.appendChild(option);
    });
  } catch (error) {
    setText("billingStatus", `Plan load failed: ${error.message}`);
  }
}

function setupChannelForm() {
  $("channelForm").addEventListener("submit", async (event) => {
    event.preventDefault();
    const payload = {
      user_id: Number($("channelUserId").value),
      channel_type: $("channelType").value,
      account_name: $("channelAccount").value.trim()
    };
    if (!payload.account_name) {
      setText("channelCreateStatus", "Account name দরকার।");
      return;
    }

    try {
      const data = await apiPost("/channels", payload);
      setText("channelCreateStatus", `Connected: #${data.channel.id}`);
      $("channelForm").reset();
      $("channelUserId").value = payload.user_id;
      $("channelType").value = payload.channel_type;
      loadChannels();
    } catch (error) {
      setText("channelCreateStatus", `Channel connect failed: ${error.message}`);
    }
  });

  $("refreshChannels").addEventListener("click", loadChannels);
}

async function loadChannels() {
  const userId = Number($("channelUserId").value || 1);
  try {
    const data = await apiGet(`/channels?user_id=${userId}`);
    if (!data.channels.length) {
      $("channelList").textContent = "No channels connected yet.";
      return;
    }
    $("channelList").innerHTML = jsonView(data.channels);
  } catch (error) {
    $("channelList").textContent = `Load failed: ${error.message}`;
  }
}

function setupBilling() {
  $("billingForm").addEventListener("submit", async (event) => {
    event.preventDefault();
    const payload = {
      user_id: Number($("billingUserId").value),
      plan_code: $("billingPlan").value,
      gateway: $("billingGateway").value,
      auto_renew: $("billingAutoRenew").checked
    };

    try {
      const data = await apiPost("/payments/session", payload);
      setText("billingStatus", `Session created. subscription_id=${data.subscription.id}`);
      $("billingSession").innerHTML = jsonView(data);
      $("activateSubscriptionId").value = data.subscription.id;
      loadSubscriptions();
    } catch (error) {
      setText("billingStatus", `Create session failed: ${error.message}`);
    }
  });

  $("activateForm").addEventListener("submit", async (event) => {
    event.preventDefault();
    const payload = {
      subscription_id: Number($("activateSubscriptionId").value),
      transaction_reference: $("activateTxn").value.trim() || `TXN-${Date.now()}`
    };
    try {
      const data = await apiPost("/billing/activate", payload);
      setText("activateStatus", `Activated: ${data.subscription.status}`);
      loadSubscriptions();
    } catch (error) {
      setText("activateStatus", `Activation failed: ${error.message}`);
    }
  });

  $("refreshSubscriptions").addEventListener("click", loadSubscriptions);
}

async function loadSubscriptions() {
  const userId = Number($("subscriptionUserId").value || 1);
  try {
    const data = await apiGet(`/billing/subscriptions?user_id=${userId}`);
    if (!data.subscriptions.length) {
      $("subscriptionList").textContent = "No subscriptions found.";
      return;
    }
    $("subscriptionList").innerHTML = jsonView(data.subscriptions);
  } catch (error) {
    $("subscriptionList").textContent = `Load failed: ${error.message}`;
  }
}

function setupYear() {
  $("year").textContent = new Date().getFullYear();
}

async function init() {
  setupLanguageToggle();
  setupComposer();
  setupApiConfig();
  setupChannelForm();
  setupBilling();
  setupYear();
  await loadPlans();
  await loadChannels();
  await loadSubscriptions();
}

init();
